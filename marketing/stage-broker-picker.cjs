const fs = require('node:fs');
const cp = require('node:child_process');
const git = (...args) => cp.execFileSync('git', args, { encoding: 'utf8' });
if (git('diff','--cached','--name-only').trim()) throw new Error('Index already contains changes');
const read = p => fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n');
const head = p => git('show',`HEAD:${p}`).replace(/\r\n/g,'\n');
const stage = (p,text) => {
  const hash = cp.execFileSync('git',['hash-object','-w','--stdin'],{input:text,encoding:'utf8'}).trim();
  git('update-index','--add','--cacheinfo',`100644,${hash},${p}`);
};
const htmlPath='Corngrid-web/public/dashboard.html';
const current=read(htmlPath);
const block=current.match(/                  <div class="sandbox-broker-picker">[\s\S]*?                  <\/div>/)[0];
let html=head(htmlPath).replace(/                  <label>Broker server\n[\s\S]*?                  <\/label>/,block);
html=html.replace(/dashboard\.css\?v=[^"\s]+/,'dashboard.css?v=20261105-broker-picker1').replace(/sandbox\.js\?v=[^"\s]+/,'sandbox.js?v=20261105-broker-picker2');
stage(htmlPath,html);
const cssPath='Corngrid-web/public/dashboard.css';
const css=read(cssPath).split('\n').filter(line=>line.startsWith('.sandbox-broker-picker')).join('\n');
stage(cssPath,head(cssPath)+'\n'+css+'\n');
const jsPath='Corngrid-web/public/sandbox.js';
const working=read(jsPath);
const functions=working.slice(working.indexOf('  let brokers = [];'),working.indexOf('  function escapeHtml'));
let js=head(jsPath).replace('  function escapeHtml',functions+'  function escapeHtml');
js=js.replace("brokerServer: $('sandbox-broker-server').value.trim(),", "brokerServer: ($('sandbox-manual-server-label').hidden ? $('sandbox-server-select').value : $('sandbox-broker-server').value).trim(),");
const bindings=working.slice(working.indexOf("    $('sandbox-broker').addEventListener"),working.indexOf("    $('sandbox-strategy').addEventListener"));
js=js.replace('  function bind() {\n','  function bind() {\n'+bindings);
stage(jsPath,js);
stage('Corngrid-web/public/mt5-brokers.json',read('Corngrid-web/public/mt5-brokers.json'));
stage('web.config',read('web.config'));
console.log(git('diff','--cached','--stat'));
