const {test}=require('node:test');
const assert=require('node:assert/strict');
const express=require('express');
const sqlite=require('sqlite3');
const register=require('../downloads-api');
test('downloads directory protects uploads, validates files, replaces atomically and restores originals',async t=>{
  const db=new sqlite.Database(':memory:');
  const app=express();app.use(express.json({limit:'256kb'}));
  const auth=role=>(req,res,next)=>req.get('X-Test-Role')===role?next():res.status(401).json({error:'Unauthorized'});
  register(app,db,auth('user'),auth('admin'),{'setup-guide':{file:'guide.pdf',downloadName:'guide.pdf'},gold:{file:'gold.set',downloadName:'gold.set'}},__dirname);
  app.get('/api/downloads/:id',(req,res)=>res.send('original'));
  await new Promise((resolve,reject)=>db.get('SELECT 1 FROM download_updates',e=>e?reject(e):resolve()));
  const server=app.listen(0);await new Promise(resolve=>server.once('listening',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));db.close();});
  const base='http://127.0.0.1:'+server.address().port;
  const req=(url,role='admin',options={})=>fetch(base+url,{...options,headers:{'X-Test-Role':role,...options.headers}});
  const upload=(id,filename,body,role='admin')=>req('/api/admin/downloads/'+id,role,{method:'PUT',headers:{'Content-Type':'application/octet-stream','X-File-Name':encodeURIComponent(filename),'X-Resource-Version':'v3.0'},body});
  assert.equal((await req('/api/admin/downloads','user')).status,401);
  assert.equal((await upload('gold','gold.set','Lots=0.01','user')).status,401);
  assert.equal((await upload('unknown','gold.set','Lots=0.01')).status,404);
  assert.equal((await upload('gold','../gold.set','Lots=0.01')).status,400);
  assert.equal((await upload('gold','gold.exe','Lots=0.01')).status,400);
  assert.equal((await upload('gold','gold.set','<script>bad</script>')).status,400);
  assert.equal((await upload('gold','gold.set','a'.repeat(128*1024+1))).status,400);
  assert.equal((await upload('gold','gold.set','Lots=0.01\nRisk=2')).status,200);
  let download=await req('/api/downloads/gold','user');
  assert.equal(await download.text(),'Lots=0.01\nRisk=2');
  assert.equal(download.headers.get('content-disposition'),'attachment; filename="gold.set"');
  assert.equal((await upload('gold','broken.set','not a preset')).status,400);
  assert.equal(await (await req('/api/downloads/gold','user')).text(),'Lots=0.01\nRisk=2');
  const pdf='%PDF-1.4\nGuide\n%%EOF';
  assert.equal((await upload('setup-guide','guide.pdf','not pdf')).status,400);
  assert.equal((await upload('setup-guide','guide.pdf',pdf)).status,200);
  assert.equal(await (await req('/api/downloads/setup-guide','user')).text(),pdf);
  const list=await (await req('/api/downloads','user')).json();
  assert.equal(list.resources.find(r=>r.id==='gold').version,'v3.0');
  assert.equal(list.resources.find(r=>r.id==='gold').custom,true);
  assert.equal((await req('/api/admin/downloads/gold','admin',{method:'DELETE'})).status,200);
  assert.equal(await (await req('/api/downloads/gold','user')).text(),'original');
});
